#!/usr/bin/env bash
# Finanzas local installer.
#
#   curl -fsSL https://raw.githubusercontent.com/fer336/finanzas/main/install.sh | bash
#
# Installs the whole system (Postgres, object storage, API, web app and a
# proxy) with Docker in ~/finanzas and serves it on http://localhost:8080.
# Re-running it updates the install and keeps your data and credentials.
#
# Environment overrides:
#   FINANZAS_DIR        install directory            (default: ~/finanzas)
#   FINANZAS_PORT       local port                   (default: 8080)
#   FINANZAS_VERSION    image tag                    (default: latest)
#   FINANZAS_REF        git ref to download from     (default: main)
#   FINANZAS_RAW_BASE   base URL for the files       (default: GitHub raw for FINANZAS_REF)
#   DEMO_EMAIL, DEMO_PASSWORD   demo account, first install only
#                               (default: demo@example.com / demo1234)

# Everything runs inside main so a partial download never executes.
main() {
  set -euo pipefail

  local dir="${FINANZAS_DIR:-$HOME/finanzas}"
  local port="${FINANZAS_PORT:-8080}"
  local ref="${FINANZAS_REF:-main}"
  local raw_base="${FINANZAS_RAW_BASE:-https://raw.githubusercontent.com/fer336/finanzas/${ref}}"

  say "Instalando Finanzas en ${dir}"

  need curl
  need docker
  if ! docker info >/dev/null 2>&1; then
    fail "Docker está instalado pero no responde. Inicialo (o agregá tu usuario al grupo docker) y volvé a correr el instalador."
  fi
  local compose
  if docker compose version >/dev/null 2>&1; then
    compose="docker compose"
  elif command -v docker-compose >/dev/null 2>&1; then
    compose="docker-compose"
  else
    fail "Falta Docker Compose. Instalalo: https://docs.docker.com/compose/install/"
  fi

  if [ -e "$dir/.git" ]; then
    fail "${dir} es un repositorio git; elegí otra carpeta con FINANZAS_DIR para no pisar sus archivos."
  fi
  mkdir -p "$dir"
  cd "$dir"

  say "Descargando la configuración..."
  download "${raw_base}/deploy/local/docker-compose.yml" docker-compose.yml
  download "${raw_base}/deploy/local/Caddyfile" Caddyfile

  if [ -f .env ]; then
    say "Usando el .env existente (tus datos y credenciales se conservan)."
    if [ -n "${FINANZAS_PORT:-}" ]; then set_env FINANZAS_PORT "$FINANZAS_PORT"; fi
    if [ -n "${FINANZAS_VERSION:-}" ]; then set_env FINANZAS_VERSION "$FINANZAS_VERSION"; fi
    port="$(env_value FINANZAS_PORT)"
    port="${port:-8080}"
  else
    umask 077
    cat > .env <<EOF
# Generated by install.sh. Keep this file private.
FINANZAS_PORT=${port}
FINANZAS_VERSION=${FINANZAS_VERSION:-latest}
POSTGRES_PASSWORD=$(random_secret)
MINIO_ROOT_PASSWORD=$(random_secret)
SECRET_KEY=$(random_secret)$(random_secret)
LOCAL_AUTH_EMAIL=${DEMO_EMAIL:-demo@example.com}
LOCAL_AUTH_PASSWORD=${DEMO_PASSWORD:-demo1234}
EOF
    say "Credenciales generadas en ${dir}/.env"
  fi

  say "Descargando imágenes (la primera vez tarda unos minutos)..."
  # Images already present still work offline; a missing one fails at "up".
  $compose pull --quiet --ignore-pull-failures
  say "Levantando los servicios..."
  $compose up -d --remove-orphans

  say "Esperando a que la API responda..."
  local url="http://localhost:${port}"
  local ok=""
  for _ in $(seq 1 90); do
    if curl -fsS "${url}/auth/local/status" 2>/dev/null | grep -q '"enabled":true'; then
      ok=1
      break
    fi
    sleep 2
  done
  if [ -z "$ok" ]; then
    printf '\n'
    $compose ps
    fail "La API no respondió a tiempo. Revisá los logs con: cd ${dir} && ${compose} logs backend"
  fi

  local email password
  email="$(env_value LOCAL_AUTH_EMAIL)"
  password="$(env_value LOCAL_AUTH_PASSWORD)"
  cat <<EOF

  ✅ Finanzas está corriendo en ${url}

     Usuario:     ${email}
     Contraseña:  ${password}

  Comandos útiles (desde ${dir}):
     ${compose} logs -f backend   ver logs
     ${compose} stop              detener
     ${compose} up -d             volver a iniciar
     ${compose} down -v           borrar todo, incluidos los datos

EOF
}

say() { printf '\033[1m==>\033[0m %s\n' "$*"; }
fail() { printf '\033[31mError:\033[0m %s\n' "$*" >&2; exit 1; }
need() { command -v "$1" >/dev/null 2>&1 || fail "Falta '$1'. Instalalo y volvé a correr el instalador."; }

download() {
  curl -fsSL "$1" -o "$2.tmp" || fail "No se pudo descargar $1"
  mv "$2.tmp" "$2"
}

random_secret() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex 24
  else
    head -c 24 /dev/urandom | od -An -tx1 | tr -d ' \n'
  fi
}

env_value() {
  grep -E "^$1=" .env | tail -n 1 | cut -d= -f2-
}

set_env() {
  if grep -qE "^$1=" .env; then
    local tmp
    tmp="$(mktemp)"
    grep -vE "^$1=" .env > "$tmp"
    printf '%s=%s\n' "$1" "$2" >> "$tmp"
    cat "$tmp" > .env
    rm -f "$tmp"
  else
    printf '%s=%s\n' "$1" "$2" >> .env
  fi
}

main "$@"
